-- Carla Modas — histórico de solicitações iniciadas no WhatsApp
-- Banco: projeto compartilhado com Sex Shop. Tabela isolada e sem acesso público.
-- O histórico NÃO comprova o envio efetivo da mensagem nem representa venda confirmada.
create table if not exists public.carla_order_intents (
 id uuid primary key default gen_random_uuid(),
 number bigint generated by default as identity unique,
 request_key uuid not null unique,
 customer_name text not null default '' check (char_length(customer_name)<=100),
 customer_note text not null default '' check (char_length(customer_note)<=400),
 fulfillment text not null default 'combinar'
   check (fulfillment in ('combinar','entrega','retirada')),
 items jsonb not null
   check(jsonb_typeof(items)='array' and jsonb_array_length(items) between 1 and 20),
 total numeric(12,2) not null default 0 check (total>=0),
 missing_prices integer not null default 0 check(missing_prices>=0),
 item_count integer not null default 0 check(item_count between 1 and 99),
 status text not null default 'whatsapp_aberto'
   check(status in ('whatsapp_aberto','em_atendimento','concluido','cancelado')),
 internal_notes text not null default '' check(char_length(internal_notes)<=1000),
 request_fingerprint text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.carla_order_intents
 add column if not exists fulfillment text not null default 'combinar'
 check (fulfillment in ('combinar','entrega','retirada'));

create index if not exists carla_order_intents_created_idx on public.carla_order_intents(created_at desc);
create index if not exists carla_order_intents_status_idx on public.carla_order_intents(status,created_at desc);
create index if not exists carla_order_intents_fingerprint_idx on public.carla_order_intents(request_fingerprint,created_at desc);

alter table public.carla_order_intents enable row level security;
revoke all on public.carla_order_intents from public,anon,authenticated;
grant select,insert,update,delete on public.carla_order_intents to service_role;

drop trigger if exists carla_orders_touch on public.carla_order_intents;
create trigger carla_orders_touch before update on public.carla_order_intents
for each row execute function public.carla_touch_updated_at();

